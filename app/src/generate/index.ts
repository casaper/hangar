import {
  chmodSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { basename, dirname, join } from 'node:path';
import type { Hangar } from '../hangar.ts';
import { tildify } from '../user-paths.ts';

/**
 * Generated-artifact plumbing.
 *
 * `hangar colours sync` never writes blindly: it builds the full desired content, compares it
 * with what is on disk, and reports each file as written / unchanged / would-change. That
 * makes `--check` a real CI-style assertion and `--dry-run` genuinely side-effect free.
 */
export type Artifact = {
  readonly path: string;
  readonly content: string;
  readonly mode?: number;
  /** Why this file exists, shown in `colours sync` output. */
  readonly what: string;
};

export type ArtifactOutcome = 'written' | 'unchanged' | 'would-change' | 'would-create';

/**
 * Why editing the file by hand is pointless, for an artifact whose source is not the palette.
 *
 * Defaulted, so every artifact that IS derived from the hues keeps its header byte for byte --
 * which is what keeps the golden delta of adding a new artifact to the new artifact.
 */
const DERIVED_FROM_PALETTE = [
  'The hues are data in src/palette.ts and everything else is derived from them;',
  'editing this file instead just means the next sync silently reverts you.',
] as const;

export const artifactHeader = (
  hangar: Hangar,
  what: string,
  why: readonly string[] = DERIVED_FROM_PALETTE,
  // Which command to re-run. Defaulted, because `colours sync` writes all but one of these --
  // and a header naming the wrong command is worse than none: it sends a reader to a command
  // that will report the file unchanged and leave them believing they have already tried.
  by = 'hangar colours sync',
): string =>
  [
    // The hangar root, not the literal `~/code/dvb_gn` this used to carry. These artifacts land
    // in `~/.claude` and at a hangar root, where a second hangar's copies sit beside them --
    // so the header naming which hangar wrote a file is the only thing distinguishing them.
    `# GENERATED by \`${by}\` (${tildify(hangar.root)}) -- do not edit by hand.`,
    `# ${what}`,
    ...why.map((line) => `# ${line}`),
  ].join('\n');

const readIfPresent = (path: string): string | undefined => {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return undefined;
  }
};

export const applyArtifact = (artifact: Artifact, dryRun: boolean): ArtifactOutcome => {
  const existing = readIfPresent(artifact.path);
  if (existing === artifact.content) return 'unchanged';
  if (dryRun) return existing === undefined ? 'would-create' : 'would-change';
  mkdirSync(dirname(artifact.path), { recursive: true });
  writeAtomically(artifact.path, artifact.content, artifact.mode);
  return 'written';
};

/**
 * Write `content` to `path` so that no reader ever sees half of it.
 *
 * tmux runs `clone-tmux-status.sh` every ten seconds for every client and every new shell
 * sources `clone-terminal.sh`, so an in-place truncate-and-write could be read mid-way, and a
 * brand-new script was briefly not executable before the `chmod`. The content goes to a temp file
 * beside the destination, already at its final mode, and is renamed over it -- atomic within one
 * directory. A destination that is a SYMLINK (a dotfiles repo managing it, say) is resolved first,
 * so the rename lands on the real file and the link survives; renaming onto the link itself would
 * have replaced it with a plain file.
 */
const writeAtomically = (path: string, content: string, declared: number | undefined): void => {
  let target = path;
  let mode = declared;
  try {
    target = realpathSync(path);
    // An in-place write kept the existing file's mode; a fresh temp file would take the umask's
    // instead, so a file somebody made 0600 would quietly become 0644. Carried over unless the
    // artifact declares its own.
    mode ??= statSync(target).mode & 0o7777;
  } catch {
    // Not there yet: write it where it was asked for.
  }
  const temp = join(dirname(target), `.${basename(target)}.${String(process.pid)}.tmp`);
  try {
    writeFileSync(temp, content, { encoding: 'utf8', ...(mode === undefined ? {} : { mode }) });
    if (mode !== undefined) chmodSync(temp, mode); // `mode` above is masked by the umask.
    renameSync(temp, target);
  } catch (error) {
    rmSync(temp, { force: true });
    throw error;
  }
};
