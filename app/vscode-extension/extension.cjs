/*
 * Hangar keys for VS Code: the clone's tmux keys, pressed in the clone's VS Code window.
 *
 * ONE extension per machine, for every hangar on it. It names no path and no repository: at
 * activation it walks up from the workspace to the nearest `hangar.config.yaml`, and the directory
 * directly under that root on the way is the clone. A window outside any hangar gets commands that
 * say so and do nothing else.
 *
 * Everything that ACTS is `bin/hangar --hangar <root> key <action> <clone>`, the same command the
 * tmux key runs, so a press here and a press in tmux cannot do different things. What is native
 * here is only what VS Code does better: a QuickPick instead of fzf, and opening or revealing a
 * picked path in THIS window.
 *
 * It also answers requests from the tmux side. A picker in the clone's tmux window that chose a
 * directory cannot reveal it in the Explorer from outside, so it writes
 * `<clone>/tmp/.hangar-ide/request.json` and raises this window; the watcher below does the rest.
 * `window.json` beside it says a window with this extension is open on the clone, which is how
 * the tmux side knows a request will be read at all.
 *
 * The manifest (`package.json`) is generated by `hangar ide vscode sync` from the CLI's key
 * table, so the chords here are the tmux ones and cannot drift from them.
 *
 * CommonJS, and nothing but Node's own modules and `vscode`: there is no build step.
 */
'use strict';

const vscode = require('vscode');
const { execFile } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

/** The hangar root and clone a directory belongs to, or undefined outside every hangar. */
const locate = (dir) => {
  let at = dir;
  for (;;) {
    const parent = path.dirname(at);
    if (fs.existsSync(path.join(parent, 'hangar.config.yaml'))) {
      return { root: parent, clone: path.basename(at), clonePath: at };
    }
    if (parent === at) return undefined;
    at = parent;
  }
};

/** Where this window is: the workspace file's directory, or else its first folder. */
const here = () => {
  const file = vscode.workspace.workspaceFile;
  if (file !== undefined && file.scheme === 'file') return locate(path.dirname(file.fsPath));
  const folder = vscode.workspace.workspaceFolders?.[0];
  return folder === undefined ? undefined : locate(folder.uri.fsPath);
};

/** `bin/hangar --hangar <root> <args…>`, resolved with its stdout and stderr. */
const hangar = (where, args) =>
  new Promise((resolve) => {
    execFile(
      path.join(where.root, 'bin', 'hangar'),
      ['--hangar', where.root, ...args],
      { cwd: where.clonePath, maxBuffer: 64 * 1024 * 1024 },
      (error, stdout, stderr) => resolve({ ok: error === null, stdout, stderr }),
    );
  });

/** The first non-empty line, which is the sentence every `hangar key` action reports. */
const firstLine = (text) =>
  text
    .split('\n')
    .map((line) => line.trim())
    .find((line) => line !== '') ?? '';

const report = (result) => {
  const line = firstLine(result.stdout) || firstLine(result.stderr);
  if (line === '') return;
  if (result.ok) void vscode.window.showInformationMessage(line);
  else void vscode.window.showErrorMessage(line);
};

const outside = () =>
  void vscode.window.showWarningMessage('This window is not a clone of any hangar.');

/** Open a clone-relative path here: a file in an editor, a directory in the Explorer. */
const openHere = async (where, row) => {
  const uri = vscode.Uri.file(path.join(where.clonePath, row));
  if (row.endsWith('/')) {
    await vscode.commands.executeCommand('workbench.view.explorer');
    await vscode.commands.executeCommand('revealInExplorer', uri);
    return;
  }
  await vscode.window.showTextDocument(uri, { preview: false });
};

/** A `hangar key … --list` call, parsed: the rows a picker offers. */
const listRows = async (where, args) => {
  const result = await hangar(where, args);
  if (!result.ok) {
    report(result);
    return undefined;
  }
  return JSON.parse(result.stdout);
};

// ---- the file reference handed to the clone's Claude Code ------------------------------------

/**
 * `@<absolute path>#<first>-<last>` for a selection, `#<line>` for one line, the bare path for a
 * whole file. Absolute, because the Claude Code it is pasted into may not be standing in the clone
 * root. A selection ending at column 0 of a line does not include that line.
 */
const refFor = (uri, selection) => {
  if (selection === undefined || selection.isEmpty) return `@${uri.fsPath}`;
  const first = selection.start.line + 1;
  let last = selection.end.line + 1;
  if (selection.end.character === 0 && last > first) last -= 1;
  return first === last ? `@${uri.fsPath}#${first}` : `@${uri.fsPath}#${first}-${last}`;
};

/** The refs a press means: the Explorer's selected resources, or the editor's selection. */
const refsFrom = (clicked, selected) => {
  if (Array.isArray(selected) && selected.length > 0) return selected.map((uri) => refFor(uri));
  if (clicked instanceof vscode.Uri) return [refFor(clicked)];
  const editor = vscode.window.activeTextEditor;
  return editor === undefined ? [] : [refFor(editor.document.uri, editor.selection)];
};

// ---- requests from the tmux side ---------------------------------------------------------------

const mailbox = (where) => path.join(where.clonePath, 'tmp', '.hangar-ide');

const answerRequest = async (where) => {
  const file = path.join(mailbox(where), 'request.json');
  let request;
  try {
    request = JSON.parse(fs.readFileSync(file, 'utf8'));
    fs.rmSync(file, { force: true });
  } catch {
    return; // not there, or half-written: the next change event brings the whole file
  }
  if (typeof request?.path === 'string') await openHere(where, request.path);
};

/** Say a window is open on the clone, and read the requests written for it. */
const watchMailbox = (context, where) => {
  const dir = mailbox(where);
  fs.mkdirSync(dir, { recursive: true });
  const presence = path.join(dir, 'window.json');
  fs.writeFileSync(presence, `${JSON.stringify({ pid: process.pid })}\n`);
  void answerRequest(where);
  const watcher = fs.watch(dir, (_event, name) => {
    if (name === 'request.json') void answerRequest(where);
  });
  context.subscriptions.push({
    dispose: () => {
      watcher.close();
      try {
        // Only our own: a second window on the same clone may have written it since.
        if (JSON.parse(fs.readFileSync(presence, 'utf8')).pid === process.pid) fs.rmSync(presence);
      } catch {
        // already gone
      }
    },
  });
};

// ---- the commands ------------------------------------------------------------------------------

/** A key whose whole answer is one line: run it, show the line. */
const reporting = (args) => async () => {
  const where = here();
  if (where === undefined) return outside();
  report(await hangar(where, [...args, where.clone]));
};

const pickAndOpen = (action) => async () => {
  const where = here();
  if (where === undefined) return outside();
  const rows = await listRows(where, ['key', action, where.clone, '--list']);
  if (rows === undefined) return;
  if (rows.length === 0) return;
  const chosen =
    rows.length === 1 && action === 'plan'
      ? rows[0]
      : await vscode.window.showQuickPick(rows, { placeHolder: `${where.clone}: ${action}` });
  if (chosen !== undefined) await openHere(where, chosen);
};

const run = async () => {
  const where = here();
  if (where === undefined) return outside();
  const names = await listRows(where, ['key', 'run', where.clone, '--list']);
  if (names === undefined || names.length === 0) return;
  const name = await vscode.window.showQuickPick(names, { placeHolder: `${where.clone}: run` });
  if (name === undefined) return;
  const files = await listRows(where, ['key', 'run', where.clone, '--list-files', name]);
  if (files === undefined) return;
  let chosen = [];
  if (files.length > 0) {
    const picked = await vscode.window.showQuickPick(files, {
      canPickMany: true,
      placeHolder: `${name}: pick files, or (all)`,
    });
    if (picked === undefined) return;
    chosen = picked.includes(files[0]) ? [] : picked;
  }
  report(
    await hangar(where, [
      'key',
      'run',
      where.clone,
      '--entry',
      name,
      ...chosen.flatMap((file) => ['--file', file]),
    ]),
  );
};

/**
 * The Explorer's selected paths, for a key pressed in it. A keybinding passes a command no
 * arguments, so the selection is read the one way VS Code offers: `copyFilePath` copies every
 * selected path, one per line, and the clipboard is put back as it was.
 */
const explorerSelection = async () => {
  const before = await vscode.env.clipboard.readText();
  await vscode.commands.executeCommand('copyFilePath');
  const copied = await vscode.env.clipboard.readText();
  await vscode.env.clipboard.writeText(before);
  return copied
    .split(/\r?\n/)
    .filter((line) => line !== '')
    .map((line) => vscode.Uri.file(line));
};

/** `C-k C-k` and `C-b C-s`: hand the refs to the clone's Claude Code, never pressing Enter. */
const paste = (asCommand) => async (clicked, selected) => {
  const where = here();
  if (where === undefined) return outside();
  const refs = refsFrom(clicked, selected);
  if (refs.length === 0) return;
  report(
    await hangar(where, [
      'key',
      'paste',
      where.clone,
      ...(asCommand ? ['--command'] : []),
      refs.join(' '),
    ]),
  );
};

const activate = (context) => {
  const register = (id, handler) =>
    context.subscriptions.push(vscode.commands.registerCommand(id, handler));
  register('hangar.gate', reporting(['key', 'gate']));
  register('hangar.fetch', reporting(['key', 'fetch']));
  register('hangar.fetchAll', reporting(['key', 'fetch', '--all']));
  register('hangar.ticket', pickAndOpen('ticket'));
  register('hangar.plan', pickAndOpen('plan'));
  register('hangar.run', run);
  register('hangar.ref', paste(false));
  register('hangar.refExplorer', async () => {
    const uris = await explorerSelection();
    await paste(false)(undefined, uris);
  });
  register('hangar.selectionCommand', paste(true));
  const where = here();
  if (where !== undefined) watchMailbox(context, where);
};

module.exports = { activate, deactivate: () => undefined };
